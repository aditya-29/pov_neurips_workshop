#!/usr/bin/env python
"""Emit RESULTS.md from the scored files: one table per experiment.

Scores are restricted to the sample_ids every model actually answered, so a
model that ran a subset never gets compared against another model's larger set.
"""
import collections, json, sys
from pathlib import Path

RUNS = {
    "chess":   "data/chess/20260824-001859-547f861a109a",
    "asl":     "data/asl/20260824-002004-e1225b96852f",
    "wbw_mcq": "data/wbw_mcq/20260824-002030-a3e45207c4ce",
}
MODELS = [("qwen35", "Qwen3.5-9B"), ("qwen3vl", "Qwen3-VL-8B"),
          ("claude", "Claude-Opus-5"), ("gpt", "GPT-5.2")]
METRICS = {
    "chess":   ["strict", "loose", "hybrid", "moves_matched"],
    "asl":     ["token_f1", "bleu", "char_similarity", "wer"],
    "wbw_mcq": ["correct", "answered", "refusal"],
}
ORDER = {
    "chess": ["video_5s", "video_10s", "video_30s", "video_1min",
              "video_2min", "video_5min", "video_10min"],
    "asl": ["video_<3s", "video_<5s", "video_<10s", "video_<15s",
            "video_<20s", "video_<25s", "video_<30s"],
    "wbw_mcq": ["static_image", "cumulative_slow", "cumulative_normal",
                "cumulative_fast", "vanishing_slow", "vanishing_normal",
                "vanishing_fast"],
}


def mean(rows, key):
    vals = [r["score_" + key] for r in rows if r.get("score_" + key) is not None]
    return sum(vals) / len(vals) if vals else float("nan")


def main():
    out = ["# Results", "",
           "Generated by `scripts/make_results_table.py` from the scored files.",
           "Each table is restricted to the sample_ids **every** listed model",
           "answered, so the columns are directly comparable.", ""]
    for exp, base in RUNS.items():
        avail = []
        for tag, label in MODELS:
            p = Path(base) / "eval" / tag / "scored.jsonl"
            if p.exists():
                avail.append((label, [json.loads(l) for l in open(p)]))
        if not avail:
            continue
        ids = set.intersection(*[{r["sample_id"] for r in v} for _, v in avail])
        avail = [(k, [r for r in v if r["sample_id"] in ids]) for k, v in avail]

        out += [f"## {exp}  (n={len(ids)} matched items)", ""]
        labels = [k for k, _ in avail]
        out += ["| metric | " + " | ".join(labels) + " |",
                "|---|" + "---|" * len(labels)]
        for met in METRICS[exp]:
            cells = [f"{mean(v, met):.4f}" for _, v in avail]
            out.append(f"| **{met}** | " + " | ".join(cells) + " |")
        out.append("")

        primary = METRICS[exp][0]
        out += [f"### {primary} by condition", "",
                "| condition | " + " | ".join(labels) + " |",
                "|---|" + "---|" * len(labels)]
        g = {k: collections.defaultdict(list) for k, _ in avail}
        for k, v in avail:
            for r in v:
                g[k][r["condition"]].append(r)
        for c in ORDER[exp]:
            if not any(g[k].get(c) for k in labels):
                continue
            cells = [f"{mean(g[k][c], primary):.4f}" if g[k].get(c) else "-"
                     for k in labels]
            out.append(f"| `{c}` | " + " | ".join(cells) + " |")
        out.append("")

    text = "\n".join(out) + "\n"
    Path("RESULTS.md").write_text(text)
    print(f"wrote RESULTS.md ({len(text)} chars, {len(out)} lines)")


if __name__ == "__main__":
    sys.exit(main())
